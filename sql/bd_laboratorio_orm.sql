-- =====================================================================
-- PARTE 2: Esquema, tablas y restricciones
-- =====================================================================

-- Para volver a crear todo desde cero, descomenta la siguiente línea:
-- DROP SCHEMA IF EXISTS catalogo CASCADE;

-- Creación del esquema de la base de datos.
CREATE SCHEMA catalogo;

-- Creación de la tabla tipo_equipo dentro del esquema catalogo.
CREATE TABLE catalogo.tipo_equipo(
                                     id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     nombre VARCHAR(100) NOT NULL UNIQUE,
                                     descripcion VARCHAR(200)
);

-- Creación de la tabla equipo dentro del esquema catalogo.
CREATE TABLE catalogo.equipo(
                                id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                codigo VARCHAR(50) NOT NULL UNIQUE,
                                nombre VARCHAR(100) NOT NULL,
                                marca VARCHAR(50) NOT NULL,
                                estado VARCHAR(50) NOT NULL,
                                cantidad INTEGER NOT NULL,
                                id_tipo BIGINT NOT NULL,

                                CONSTRAINT chk_equipo_estado
                                    CHECK (estado IN ('Disponible', 'En mantenimiento', 'Fuera de servicio')),

                                CONSTRAINT chk_equipo_cantidad
                                    CHECK (cantidad >= 0),

    -- Sin ON DELETE CASCADE: no se puede eliminar un tipo que tenga equipos
                                CONSTRAINT fk_equipo_tipo FOREIGN KEY (id_tipo)
                                    REFERENCES catalogo.tipo_equipo (id_tipo)
);


